import numpy as np
a=np.array([1,2,3,4,5])
print('values of Array')
print(a)
print('Data type of Array:',a.dtype)

a=np.array([1,2,3,4,5],dtype='i2')
print('values of Array')
print(a)
print('Data type of Array:',a.dtype)

a=np.array([1,2,3,4,5],dtype='S')
print('values of Array')
print(a)
print('Data type of Array:',a.dtype)

a=np.array([1,2,3,4,5],dtype='f')
print('values of Array')
print(a)
print('Data type of Array:',a.dtype)
